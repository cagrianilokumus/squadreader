// Returns a served photo URL for a vehicle blueprint class, or null when we
// have no photo for it (caller should hide the <img> / show a placeholder).
export function vehiclePhotoUrl(classShort: string | null | undefined): string | null {
  if (!classShort) return null;
  const slug = VEHICLE_PHOTO.get(vehicleDisplayName(classShort));
  return slug ? `./icons/photos/${slug}.webp` : null;
}
