// Lookup helper. Falls back to a cleaned-up version of the raw blueprint
// name (BP_ and _C stripped, underscores -> spaces) for emplacements and
// other classes that aren't in the curated table.
export function vehicleDisplayName(classShort: string | null | undefined): string {
  if (!classShort) return "?";
  const exact = VEHICLE_DISPLAY_NAMES.get(classShort);
  if (exact) return exact;
  return classShort
    .replace(/^BP_/, "")
    .replace(/_C$/, "")
    .replace(/_/g, " ");
}
